#!/usr/bin/env python3
"""Regenerates the tables in docs/CONFIG.md and docs/LOGGING.md from the single sources of truth:

    shared/include/x4/config_schema.def  -> docs/CONFIG.md   (between GENERATED:config markers)
    shared/include/x4/errors.def         -> docs/LOGGING.md  (between GENERATED:errors markers)

    python tools/gen_docs.py          # rewrite the docs
    python tools/gen_docs.py --check  # CI: exit 1 if the docs drifted from the code
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "shared/include/x4/config_schema.def"
ERRORS = ROOT / "shared/include/x4/errors.def"
SAFETY = ROOT / "shared/include/x4/safety.h"
CONFIG_MD = ROOT / "docs/CONFIG.md"
LOGGING_MD = ROOT / "docs/LOGGING.md"

CFG_RE = re.compile(r'^X4_CFG\(\s*(\w+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*([\w| ]+?)\s*,\s*"(.*)"\)\s*$')
ERR_RE = re.compile(r'^X4_ERR\(\s*(\d+)\s*,\s*(\w+)\s*,\s*"(.*)"\)\s*$')
SECTION_RE = re.compile(r"^// ---- (.+?) -+")


def config_table():
    rows, section = [], None
    for line in SCHEMA.read_text().splitlines():
        m = SECTION_RE.match(line)
        if m:
            section = m.group(1)
            rows.append(("section", section))
            continue
        m = CFG_RE.match(line)
        if m:
            rows.append(("opt", m.groups()))
    out = []
    for kind, val in rows:
        if kind == "section":
            out.append(f"\n**{val}**\n")
            out.append("| option | default | range | unit | scope | safety | reboot | meaning |")
            out.append("|---|---|---|---|---|---|---|---|")
            continue
        name, d, mn, mx, unit, scope, flags, doc = val
        safety = "tighten-only ↓" if "SAFE_MAX" in flags else "tighten-only ↑" if "SAFE_MIN" in flags else ""
        reboot = "yes" if "REBOOT" in flags else ""
        out.append(f"| `{name}` | {d} | {mn}…{mx} | {unit} | {scope.lower()} | {safety} | {reboot} | {doc} |")
    return "\n".join(out).strip() + "\n"


def safety_table():
    out = ["| constant | value | meaning |", "|---|---|---|"]
    lines = SAFETY.read_text().splitlines()
    for i, line in enumerate(lines):
        m = re.match(r"\s*constexpr \w+ (k\w+) = (\d+);[ \t]*(?://[ \t]*(.*))?$", line)
        if not m:
            continue
        doc = m.group(3) or ""
        if not doc:  # use the comment block directly above
            j, block = i - 1, []
            while j >= 0 and lines[j].strip().startswith("//") and "----" not in lines[j]:
                block.insert(0, lines[j].strip()[2:].strip())
                j -= 1
            doc = " ".join(block)
        out.append(f"| `{m.group(1)}` | {m.group(2)} | {doc.replace('|', '/')} |")
    return "\n".join(out) + "\n"


def error_table():
    out = ["| code | name | meaning / what to check |", "|---|---|---|"]
    for line in ERRORS.read_text().splitlines():
        m = ERR_RE.match(line)
        if m:
            out.append(f"| {m.group(1)} | `{m.group(2)}` | {m.group(3)} |")
    return "\n".join(out) + "\n"


def splice(text, tag, body):
    begin, end = f"<!-- BEGIN GENERATED:{tag} -->", f"<!-- END GENERATED:{tag} -->"
    if begin not in text or end not in text:
        raise SystemExit(f"markers for {tag} missing")
    pre, rest = text.split(begin, 1)
    _, post = rest.split(end, 1)
    return f"{pre}{begin}\n<!-- generated by tools/gen_docs.py: edit the .def files, not this table -->\n{body}{end}{post}"


def main():
    check = "--check" in sys.argv
    jobs = [
        (CONFIG_MD, [("config", config_table()), ("safety", safety_table())]),
        (LOGGING_MD, [("errors", error_table())]),
    ]
    drift = False
    for path, parts in jobs:
        old = path.read_text()
        new = old
        for tag, body in parts:
            new = splice(new, tag, body)
        if new != old:
            drift = True
            if not check:
                path.write_text(new)
                print(f"updated {path.relative_to(ROOT)}")
    if check and drift:
        print("docs out of date: run python tools/gen_docs.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
