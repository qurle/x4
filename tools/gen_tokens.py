#!/usr/bin/env python3
"""Generates core/src/ui/tokens.h from ui/tokens.json (the design source of truth).

    python tools/gen_tokens.py          # write
    python tools/gen_tokens.py --check  # exit 1 if tokens.h is out of date (CI)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "ui" / "tokens.json"
DST = ROOT / "core" / "src" / "ui" / "tokens.h"

EASE = {
    "linear": "lv_anim_path_linear",
    "ease_in": "lv_anim_path_ease_in",
    "ease_out": "lv_anim_path_ease_out",
    "ease_in_out": "lv_anim_path_ease_in_out",
    "overshoot": "lv_anim_path_overshoot",
    "bounce": "lv_anim_path_bounce",
}


def camel_to_snake(s):
    out = ""
    for ch in s:
        out += ("_" + ch.lower()) if ch.isupper() else ch
    return out


def render(t):
    L = []
    L.append("// GENERATED by tools/gen_tokens.py from ui/tokens.json. Do not edit by hand.")
    L.append("// Values marked ASSUMPTION in ui/tokens.json until the Figma tokens are imported.")
    L.append("#pragma once")
    L.append('#include "lvgl.h"')
    L.append("")
    L.append("namespace x4ui {")
    L.append("namespace tok {")
    L.append("")
    L.append("// ---- colour (RGB hex) ----")
    for k, v in t["color"].items():
        hexv = v["value"].lstrip("#")
        L.append(f"constexpr uint32_t k{k[0].upper()}{k[1:]} = 0x{hexv.upper()};  // {v.get('use', '')}")
    L.append("inline lv_color_t c(uint32_t hex) { return lv_color_hex(hex); }")
    L.append("")
    L.append("// ---- spacing (px) ----")
    for k, v in t["space"].items():
        L.append(f"constexpr int32_t kSpace{k.upper()} = {v};")
    L.append("// ---- radius (px) ----")
    for k, v in t["radius"].items():
        val = "LV_RADIUS_CIRCLE" if v >= 999 else str(v)
        L.append(f"constexpr int32_t kRadius{k[0].upper()}{k[1:]} = {val};")
    L.append("// ---- border (px) ----")
    for k, v in t["border"].items():
        L.append(f"constexpr int32_t kBorder{k[0].upper()}{k[1:]} = {v};")
    L.append("// ---- layout (px, from Figma) ----")
    for k, v in t.get("layout", {}).items():
        L.append(f"constexpr int32_t k{k[0].upper()}{k[1:]} = {v['value']};  // {v.get('use', '')}")
    L.append("")
    L.append("// ---- motion ----")
    for k, v in t["motion"].items():
        L.append(f"constexpr uint32_t kMs{k[0].upper()}{k[1:]} = {v['ms']};  // {v.get('use', '')}")
    for k, v in t["motion"].items():
        L.append(f"inline lv_anim_path_cb_t path{k[0].upper()}{k[1:]}() {{ return {EASE[v['ease']]}; }}")
    L.append("")
    L.append(f"constexpr int32_t kScreenW = {t['screen']['width']};")
    L.append(f"constexpr int32_t kScreenH = {t['screen']['height']};")
    L.append("")
    L.append("}  // namespace tok")
    L.append("")
    L.append("// ---- fonts (generated by tools/gen_fonts.sh) ----")
    seen = set()
    for k, v in t["font"].items():
        if v["lvgl"] not in seen:
            L.append(f"extern \"C\" {{ extern const lv_font_t {v['lvgl']}; }}")
            seen.add(v["lvgl"])
    L.append("namespace tok {")
    for k, v in t["font"].items():
        L.append(f"inline const lv_font_t* font{k[0].upper()}{k[1:]}() {{ return &{v['lvgl']}; }}  // {v['family']} {v['size']}")
    L.append("}  // namespace tok")
    L.append("}  // namespace x4ui")
    L.append("")
    return "\n".join(L)


def main():
    t = json.loads(SRC.read_text())
    out = render(t)
    if "--check" in sys.argv:
        if not DST.exists() or DST.read_text() != out:
            print(f"{DST} is out of date: run python tools/gen_tokens.py", file=sys.stderr)
            return 1
        return 0
    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text(out)
    print(f"wrote {DST}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
