#!/usr/bin/env python3
"""Converts ui/assets/figma/*.png (except _reference-*) into LVGL 9 images (RGB565A8) in
core/src/ui/assets/. Files starting with "_" are design references only and are not converted.

    pip install pillow
    python tools/gen_assets.py          # write
    python tools/gen_assets.py --check  # CI: exit 1 if the C files are stale

RGB565A8 layout (LVGL 9): a plane of little-endian RGB565 pixels (stride = w*2) followed by a
plane of 8-bit alpha (stride = w).
"""
import pathlib
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "ui" / "assets" / "figma"
DST = ROOT / "core" / "src" / "ui" / "assets"


def cname(path):
    return "x4_img_" + path.stem.replace("-", "_")


def convert(path):
    im = Image.open(path).convert("RGBA")
    w, h = im.size
    px = im.load()
    color = bytearray()
    alpha = bytearray()
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            color += bytes((v & 0xFF, v >> 8))
            alpha.append(a)
    data = color + alpha
    name = cname(path)
    lines = [
        f"// GENERATED by tools/gen_assets.py from ui/assets/figma/{path.name}. Do not edit.",
        '#include "lvgl.h"',
        "",
        f"static const uint8_t {name}_map[] = {{",
    ]
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines += [
        "};",
        "",
        f"const lv_image_dsc_t {name} = {{",
        "  .header = {",
        "    .magic = LV_IMAGE_HEADER_MAGIC,",
        "    .cf = LV_COLOR_FORMAT_RGB565A8,",
        "    .flags = 0,",
        f"    .w = {w},",
        f"    .h = {h},",
        f"    .stride = {w * 2},",
        "  },",
        f"  .data_size = sizeof({name}_map),",
        f"  .data = {name}_map,",
        "};",
        "",
    ]
    return name, w, h, "\n".join(lines)


def main():
    check = "--check" in sys.argv
    outs = {}
    header = [
        "// GENERATED by tools/gen_assets.py. Images exported from the Figma file (ui/assets/figma/).",
        "#pragma once",
        '#include "lvgl.h"',
        "",
        'extern "C" {',
    ]
    for p in sorted(SRC.glob("*.png")):
        if p.name.startswith("_"):
            continue
        name, w, h, text = convert(p)
        outs[DST / f"{name}.c"] = text
        header.append(f"extern const lv_image_dsc_t {name};  // {w}x{h} from {p.name}")
    header += ["}", ""]
    outs[DST / "assets.h"] = "\n".join(header)
    stale = [f for f, t in outs.items() if not f.exists() or f.read_text() != t]
    if check:
        if stale:
            print("assets out of date: run python tools/gen_assets.py", file=sys.stderr)
            return 1
        return 0
    DST.mkdir(parents=True, exist_ok=True)
    for f in stale:
        f.write_text(outs[f])
        print(f"wrote {f.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
